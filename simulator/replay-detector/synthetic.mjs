/**
 * Writes a synthetic recording for tests and demonstrations: a straight ride north at GSU with one
 * hard stop and one curb hit. It is generated data, labeled `"source": "synthetic"`, with the
 * endpoints already outside the file (`"trimmed": true`), and says nothing about real rides.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const G = 9.80665;
const METERS_PER_DEGREE = 111_320;

export function writeSyntheticRecording(directory, { startMs = 1_760_000_000_000, durationMs = 20_000, brakeAtMs = 6000, bumpAtMs = 14_000 } = {}) {
  mkdirSync(directory, { recursive: true });
  const speedAt = (t) => {
    if (t < brakeAtMs) return 7;
    if (t < brakeAtMs + 1500) return 7 - 5 * (t - brakeAtMs) / 1500;
    if (t < brakeAtMs + 4000) return 2 + 4 * (t - brakeAtMs - 1500) / 2500;
    return 6;
  };
  const motion = ['t_ms,ax,ay,az,gx,gy,gz'];
  const gps = ['t_ms,lat,lon,speed_mps,accuracy_m'];
  let travelled = 0;
  for (let t = 0; t <= durationMs; t += 20) {
    travelled += speedAt(t) * 0.02;
    const braking = t >= brakeAtMs && t < brakeAtMs + 1200 ? 0.5 * G : 0;
    const bump = t >= bumpAtMs && t < bumpAtMs + 60 ? 1.8 * G : 0;
    motion.push([startMs + t, braking.toFixed(4), 0, bump.toFixed(4), 0, 0, G].join(','));
    if (t % 1000 === 0) {
      // One fix with unknown speed, to exercise the blank-cell rule.
      const speed = t === 2000 ? '' : speedAt(t).toFixed(2);
      gps.push([startMs + t, (33.7531 + travelled / METERS_PER_DEGREE).toFixed(7), (-84.3853).toFixed(7), speed, 5].join(','));
    }
  }
  writeFileSync(join(directory, 'motion.csv'), motion.join('\n') + '\n');
  writeFileSync(join(directory, 'gps.csv'), gps.join('\n') + '\n');
  writeFileSync(join(directory, 'labels.csv'), ['t_ms,type', `${startMs + brakeAtMs},hard_brake`, `${startMs + bumpAtMs},bump`].join('\n') + '\n');
  writeFileSync(join(directory, 'meta.json'), JSON.stringify({
    format: 1, ride_id: 'synthetic', source: 'synthetic', trimmed: true,
    note: 'Generated by simulator/replay-detector/synthetic.mjs. Not a real ride.',
  }, null, 2) + '\n');
  return directory;
}
